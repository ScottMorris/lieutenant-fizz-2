//   bun tools/font/export-fizz1.ts            writes the file
//   bun tools/font/export-fizz1.ts --check    regenerates in memory and exits non-zero with a diff if the committed file differs;
//                                             prints a message and exits 0 when no Fizz 1 checkout is present (CI has none)
// FIZZ1 names the Fizz 1 checkout; it defaults to ~/source/liminal-hq/lieutenant-fizz.
// The export follows the Fizz 1 DOS port's `m4/export-ui.ts` (the same glyph rows, leftmost pixel in the highest bit), limited to
// printable ASCII and the typographic marks the game's captions and toasts use, so the DOS executable stays small.

import { existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { homedir, tmpdir } from 'node:os';

const FIZZ1 = process.env.FIZZ1 ?? `${homedir()}/source/liminal-hq/lieutenant-fizz`;
const OUT = new URL('../../crates/fizz-view/src/fizz_font_data.rs', import.meta.url).pathname;
/** The Fizz 1 commit the data was taken from. */
const FIZZ1_COMMIT = '4bce036';
/** The Fizz 1 DOS port commit whose exporter this follows. */
const DOS_PORT_COMMIT = '221dd6c';
const MARKS = '—–…‘’“”·';

const wanted = (cp: number) => (cp >= 0x21 && cp <= 0x7e) || MARKS.includes(String.fromCodePoint(cp));

async function emit(): Promise<string> {
  const { RAW, EXTRA } = await import(`${FIZZ1}/packages/engine/src/font/fizz-glyphs.ts`);
  const glyphs = new Map<number, { w: number; rows: number[] }>();
  for (const [key, grid] of Object.entries({ ...RAW, ...EXTRA }) as [string, string][]) {
    const chars = Array.from(key);
    if (chars.length !== 1 || !wanted(chars[0].codePointAt(0)!)) continue;
    const rows = grid.split('/');
    const w = Math.max(...rows.map((r) => r.length));
    glyphs.set(chars[0].codePointAt(0)!, {
      w,
      rows: rows.map((r) => [...r.padEnd(w, '.')].reduce((bits, c) => (bits << 1) | (c === '#' ? 1 : 0), 0)),
    });
  }
  const out: string[] = [];
  out.push("// Fizz 1's pixel font as Rust data: proportional glyphs, mixed case, with descenders.");
  out.push('//');
  out.push('// (c) Copyright 2026 Liminal HQ, Scott Morris');
  out.push('// SPDX-License-Identifier: Apache-2.0 OR MIT');
  out.push('//');
  out.push('// @generated by tools/font/export-fizz1.ts. Do not edit; run `bun tools/font/export-fizz1.ts` (`--check` verifies it).');
  out.push(`// Source: Fizz 1 (lieutenant-fizz) commit ${FIZZ1_COMMIT}, packages/engine/src/font/fizz-glyphs.ts (\`RAW\` and \`EXTRA\`), the owner's own`);
  out.push(`// code under the same licence; the row format follows the Fizz 1 DOS port (fizz-dos commit ${DOS_PORT_COMMIT}, m4/export-ui.ts).`);
  out.push(`// ${glyphs.size} glyphs: printable ASCII and the dashes, ellipsis, quotes and middle dot.`);
  out.push('');
  out.push('/// One glyph: its code point, its width and its rows from the top of a capital letter, the leftmost pixel in the highest bit.');
  out.push('pub struct Glyph {');
  out.push('    pub cp: u32,');
  out.push('    pub w: u8,');
  out.push("    pub rows: &'static [u16],");
  out.push('}');
  out.push('');
  out.push('/// Sorted by code point.');
  out.push('pub static FONT: &[Glyph] = &[');
  for (const [cp, g] of [...glyphs.entries()].sort((a, b) => a[0] - b[0]))
    out.push(`    Glyph { cp: ${cp}, w: ${g.w}, rows: &[${g.rows.join(', ')}] },`);
  out.push('];');
  return out.join('\n') + '\n';
}

if (process.argv.includes('--check')) {
  if (!existsSync(`${FIZZ1}/packages/engine/src/font/fizz-glyphs.ts`)) {
    console.log(`font check skipped: no Fizz 1 checkout at ${FIZZ1} (set FIZZ1 to check the committed data)`);
    process.exit(0);
  }
  const want = await emit();
  const have = readFileSync(OUT, 'utf8');
  if (want === have) {
    console.log('fizz_font_data.rs is current');
    process.exit(0);
  }
  const dir = mkdtempSync(`${tmpdir()}/font-check-`);
  writeFileSync(`${dir}/regenerated.rs`, want);
  console.error(spawnSync('diff', ['-u', OUT, `${dir}/regenerated.rs`], { encoding: 'utf8' }).stdout);
  console.error('fizz_font_data.rs is out of date: run bun tools/font/export-fizz1.ts');
  process.exit(1);
}
writeFileSync(OUT, await emit());
