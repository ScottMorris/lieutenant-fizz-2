// SPDX-License-Identifier: Apache-2.0 OR MIT
//
//   bun tools/sprites/emit-rust.ts           regenerates the file
//   bun tools/sprites/emit-rust.ts --check   regenerates in memory; exits non-zero with a diff if the committed file differs
// Sets are read in file-name order and sprites in file order, so the output depends only on the committed grids.

import { mkdtempSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { LETTERS, ROOT, SPRITES_DIR, TRANSPARENT, parseSet } from './lib.ts';

const OUT = `${ROOT}crates/fizz-view/src/sprites_data.rs`;

export function emit(): string {
  const files = readdirSync(SPRITES_DIR)
    .filter((f) => f.endsWith('.json'))
    .sort();
  const names = new Set<string>();
  const items: string[] = [];
  for (const f of files) {
    const set = parseSet(readFileSync(`${SPRITES_DIR}/${f}`, 'utf8'), f);
    for (const s of set.sprites) {
      if (names.has(s.name)) throw new Error(`${f}: sprite name ${s.name} is used in more than one file`);
      names.add(s.name);
      const rows = s.rows.map((r) => `            ${[...r].map((c) => (c === TRANSPARENT ? '255' : String(LETTERS.indexOf(c)))).join(', ')},`);
      items.push(
        `    // ${f}: ${s.name}, source ${s.source}\n    Sprite {\n        name: "${s.name}",\n        w: ${s.w},\n        h: ${s.h},\n        ax: ${s.anchor[0]},\n        ay: ${s.anchor[1]},\n        pixels: &[\n${rows.join('\n')}\n        ],\n    },`,
      );
    }
  }
  return `// Generated EGA-indexed sprite data for the presenters; do not edit.
//
// Generated by tools/sprites/emit-rust.ts from ${files.map((f) => `assets/sprites/${f}`).join(', ')}.
// Regenerate with \`bun tools/sprites/emit-rust.ts\`; \`--check\` fails if this file is out of date.
//
// (c) Copyright 2026 Liminal HQ, Scott Morris
// SPDX-License-Identifier: Apache-2.0 OR MIT

/// One sprite: \`w * h\` bytes of EGA index 0..=15, or 255 for transparent, row by row from the top left, and the anchor (feet and
/// centre unless a set says otherwise) in pixels from the top left.
pub struct Sprite {
    pub name: &'static str,
    pub w: u8,
    pub h: u8,
    pub ax: i8,
    pub ay: i8,
    pub pixels: &'static [u8],
}

/// Every sprite, in set-file order.
pub static SPRITES: &[Sprite] = &[
${items.join('\n')}
];

/// The sprite called \`name\`, if there is one.
pub fn sprite(name: &str) -> Option<&'static Sprite> {
    SPRITES.iter().find(|s| s.name == name)
}
`;
}

if (import.meta.main) {
  const text = emit();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {
      // A missing file differs from any output.
    }
    if (current !== text) {
      const dir = mkdtempSync(`${tmpdir()}/sprites-check-`);
      writeFileSync(`${dir}/expected.rs`, text);
      const d = spawnSync('diff', ['-u', OUT, `${dir}/expected.rs`], { encoding: 'utf8' });
      process.stderr.write((d.stdout ?? '').split('\n').slice(0, 60).join('\n'));
      console.error('\ncrates/fizz-view/src/sprites_data.rs is out of date; run: bun tools/sprites/emit-rust.ts');
      process.exit(1);
    }
    console.log('sprites_data.rs: up to date');
  } else {
    writeFileSync(OUT, text);
  }
}
