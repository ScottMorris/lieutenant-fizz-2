//
// (c) Copyright 2026 Liminal HQ, Scott Morris
// SPDX-License-Identifier: Apache-2.0 OR MIT
//
//   bun tools/music/generate.ts           writes crates/fizz-music/data/<song>-opl2.bin, <song>-opl3.bin and src/data.rs
//   bun tools/music/generate.ts --check   regenerates in memory; exits non-zero with a diff if a committed file differs
// Both modes first run the refusal checks and the note-parity check (tools/music/verify.ts) and stop if any fails. The output
// depends only on the committed song source, the pinned Undertone and the converter: there is no clock and no randomness. Every
// song-specific number (counts, loop point, hashes) is generated into data.rs, so swapping the song is a data-only change.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { songBars, songSeconds } from '../../assets/music/song.ts';
import { MANIFEST, TRACKS, songById } from '../../assets/music/songs.ts';
import { encode, fnv1a } from './format.ts';
import { lower, MAX_WRITES_PER_TICK, type Arrangement, type Kind } from './lower.ts';
import { RESERVED_REGISTERS, parity, parseManifest, refusals } from './verify.ts';

export const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const CRATE = `${ROOT}crates/fizz-music/`;
export const DATA_RS = `${CRATE}src/data.rs`;
export const binPath = (id: string, kind: Kind): string => `${CRATE}data/${id}-${kind}.bin`;
export const manifestPath = (id: string): string => `${ROOT}assets/music/notes/${id}.txt`;

export interface Lowered {
  id: string;
  title: string;
  placeholder: boolean;
  bpm: number;
  bars: number;
  seconds: number;
  arrangements: Record<Kind, Arrangement>;
}

/** Lowers every song in the source to both arrangements and runs the checks; throws with every problem found. */
export function lowerAll(): Lowered[] {
  const problems: string[] = [];
  const out = Object.keys(TRACKS).map((id) => {
    const layout = songById(id);
    const arrangements = { opl2: lower(layout, 'opl2'), opl3: lower(layout, 'opl3') };
    const manifest = existsSync(manifestPath(id)) ? parseManifest(readFileSync(manifestPath(id), 'utf8')) : null;
    for (const kind of ['opl2', 'opl3'] as const) {
      const a = arrangements[kind];
      for (const p of refusals(a)) problems.push(`${id} ${kind}: [${p.check}] ${p.message}`);
      if (manifest) {
        for (const p of parity(a, manifest, layout.song.bpm)) problems.push(`${id} ${kind}: [${p.check}] ${p.message}`);
      } else problems.push(`${id}: no note list at assets/music/notes/${id}.txt (run bun tools/music/notes.ts)`);
    }
    return {
      id,
      title: layout.entry.title,
      placeholder: layout.entry.placeholder,
      bpm: layout.song.bpm,
      bars: songBars(layout.song),
      seconds: songSeconds(layout.song),
      arrangements,
    };
  });
  if (problems.length) throw new Error(`the music was refused:\n${problems.map((p) => `  ${p}`).join('\n')}`);
  return out;
}

const hex = (n: number, width = 2): string => `0x${n.toString(16).padStart(width, '0')}`;
const rustStr = (s: string): string => JSON.stringify(s);

function arrangementRust(id: string, a: Arrangement): string {
  const dropped = a.dropped.map((d) => `        Dropped { tick: ${d.tick}, part: ${rustStr(d.part)}, midi: ${d.midi} },`).join('\n');
  return `    Arrangement {
        records: include_bytes!("../data/${id}-${a.kind}.bin"),
        record_count: ${a.records.length},
        loop_start: ${a.loopStart},
        prelude_ticks: ${a.preludeTicks},
        loop_ticks: ${a.loopTicks},
        notes: ${a.notes},
        drum_hits: ${a.drumHits},
        max_writes_per_tick: ${a.maxWritesPerTick},
        hash: ${hex(fnv1a(a.records), 8)},
        channels: &[${a.channels.join(', ')}],
        dropped: &[${dropped ? `\n${dropped}\n        ` : ''}],
    }`;
}

export function emitRust(songs: Lowered[]): string {
  const level = Object.keys(TRACKS).indexOf(MANIFEST.level);
  const rows = songs
    .map(
      (s) => `    Song {
        id: ${rustStr(s.id)},
        title: ${rustStr(s.title)},
        placeholder: ${s.placeholder},
        bpm: ${s.bpm},
        bars: ${s.bars},
        opl2: ${arrangementRust(s.id, s.arrangements.opl2).replace(/\n/g, '\n    ').trimStart()},
        opl3: ${arrangementRust(s.id, s.arrangements.opl3).replace(/\n/g, '\n    ').trimStart()},
    },`,
    )
    .join('\n');
  return `// Generated music data for the level song; do not edit.
//
// Generated by tools/music/generate.ts from the song source under assets/music/ (see docs/MUSIC.md), lowered by tools/music/lower.ts.
// Regenerate with \`bun tools/music/generate.ts\`; \`--check\` fails if this file or a \`data/*.bin\` file is out of date.
//
// (c) Copyright 2026 Liminal HQ, Scott Morris
// SPDX-License-Identifier: Apache-2.0 OR MIT
//
// Provenance: the lowering is adapted from \`m4/sound/fizz-dos/music.ts\`, \`song.ts\` and \`patches.ts\` of ScottMorris/lieutenant-fizz-dos
// at commit 221dd6c, the same author's code, MIT there and dual-licensed here; the song is Fizz 1's "Crater Fields" track, a placeholder.
//
// Each \`records\` file is 4-byte records in the layout of \`fizz_sfx::OplStep\`: register low byte, value, then a little-endian u16
// with the register bank in its top bit and the ticks (560 Hz) to wait after the write in the low 15. \`hash\` is the 32-bit FNV-1a of
// one pass (the prelude, then one loop) over each record's due tick (u32 little-endian, from the first record), bank, register and value.
// \`prelude_ticks\` is the time from the first record to record \`loop_start\`; \`loop_ticks\` is the time from \`loop_start\` round to
// \`loop_start\` again. The effects' channels 5 and 14 and the registers 0x104 and 0x105 are never written (the generator refuses them).

use crate::{Arrangement, Dropped, Song};

/// The registers (low bytes, either bank) of the effects' channels 5 and 14, which no music stream writes.
#[rustfmt::skip]
pub(crate) static RESERVED_REGISTERS: [u8; ${RESERVED_REGISTERS.length}] = [${RESERVED_REGISTERS.map((r) => hex(r)).join(', ')}];

/// The most register writes a music stream puts in one tick.
pub(crate) const MAX_WRITES_PER_TICK: u32 = ${MAX_WRITES_PER_TICK};

/// The index in [\`SONGS\`] of the song the level plays (\`MANIFEST.level\` in assets/music/songs.ts).
pub(crate) const LEVEL: usize = ${level};

/// Every song of the source.
#[rustfmt::skip]
pub(crate) static SONGS: [Song; ${songs.length}] = [
${rows}
];
`;
}

/** Everything the generator writes, as path and bytes. */
export function outputs(): { path: string; bytes: Uint8Array | string }[] {
  const songs = lowerAll();
  const files: { path: string; bytes: Uint8Array | string }[] = [];
  for (const s of songs) {
    for (const kind of ['opl2', 'opl3'] as const) files.push({ path: binPath(s.id, kind), bytes: encode(s.arrangements[kind].records) });
  }
  files.push({ path: DATA_RS, bytes: emitRust(songs) });
  return files;
}

const rel = (p: string): string => p.replace(ROOT, '');

function main(): number {
  let files: ReturnType<typeof outputs>;
  try {
    files = outputs();
  } catch (e) {
    console.error((e as Error).message);
    return 1;
  }
  if (!process.argv.includes('--check')) {
    mkdirSync(`${CRATE}data`, { recursive: true });
    for (const f of files) writeFileSync(f.path, f.bytes);
    for (const s of lowerAll()) {
      for (const kind of ['opl2', 'opl3'] as const) {
        const a = s.arrangements[kind];
        console.log(`${s.id} ${kind}: ${a.records.length} records, ${a.records.length * 4} bytes, ${a.loopTicks} ticks, ${a.notes} notes, ${a.dropped.length} dropped, max ${a.maxWritesPerTick} writes a tick`);
      }
    }
    return 0;
  }
  let stale = 0;
  for (const f of files) {
    const want = typeof f.bytes === 'string' ? Buffer.from(f.bytes) : Buffer.from(f.bytes);
    let have: Buffer | null = null;
    try {
      have = readFileSync(f.path);
    } catch {
      // A missing file differs from any output.
    }
    if (have !== null && have.equals(want)) continue;
    stale++;
    console.error(`${rel(f.path)} is out of date`);
    if (typeof f.bytes === 'string' && have !== null) {
      const dir = mkdtempSync(`${tmpdir()}/music-check-`);
      writeFileSync(`${dir}/expected.rs`, f.bytes);
      const d = spawnSync('diff', ['-u', f.path, `${dir}/expected.rs`], { encoding: 'utf8' });
      process.stderr.write((d.stdout ?? '').split('\n').slice(0, 40).join('\n'));
    }
  }
  if (stale) {
    console.error('\nrun: bun tools/music/generate.ts');
    return 1;
  }
  console.log(`fizz-music data: up to date (${files.length} files)`);
  return 0;
}

if (import.meta.main) process.exit(main());
