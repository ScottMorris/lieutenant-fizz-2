//   bun tools/music/notes.ts           regenerates assets/music/notes/<song>.txt
//   bun tools/music/notes.ts --check   regenerates in memory; exits non-zero with a diff if the committed file differs
//   bun tools/music/notes.ts --print   prints the list instead of writing it
// The list depends only on the committed source and the pinned Undertone: there is no clock and no randomness. It is the parity
// manifest the lowering generator and the Web player are held to.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { countsByPart, noteEvents, streamLabels, tickSeconds, TICKS_PER_BAR } from '../../assets/music/events.ts';
import { songBars, songSeconds } from '../../assets/music/song.ts';
import { MANIFEST, songById } from '../../assets/music/songs.ts';

export const ROOT = fileURLToPath(new URL('../../', import.meta.url));

/** The text of the note list for one song. */
export function render(id: string): string {
  const layout = songById(id);
  const { song, sections, entry } = layout;
  const events = noteEvents(layout);
  const labels = streamLabels(song);
  const counts = countsByPart(events, labels);
  const lines = [
    `# Note list for the song "${id}" (${entry.title}${entry.placeholder ? ', a placeholder: Fizz 1\'s track' : ''}).`,
    '# Generated by `bun tools/music/notes.ts`; do not edit. `--check` fails if this file is stale.',
    `# bpm ${song.bpm}, ${songBars(song)} bars, ${songSeconds(song).toFixed(2)} s, ${TICKS_PER_BAR} ticks to a bar, ${events.length} events.`,
    `# sections: ${sections.map((s) => `${s.name} ${s.cycles}@${s.startBar}`).join(', ')}`,
    `# events per part: ${labels.map((l) => `${l} ${counts[l]}`).join(', ')}`,
    '# columns: tick  seconds  part  midi-or-noise  length-ticks  velocity',
  ];
  for (const e of events) {
    lines.push(
      [
        String(e.tick).padStart(5),
        tickSeconds(song, e.tick).toFixed(3).padStart(7),
        e.part.padEnd(14),
        (e.noise ?? String(e.midi)).padEnd(5),
        String(e.length).padStart(3),
        String(e.velocity).padStart(3),
      ].join(' '),
    );
  }
  return `${lines.join('\n')}\n`;
}

export const pathFor = (id: string): string => `${ROOT}assets/music/notes/${id}.txt`;

function main(): number {
  const id = MANIFEST.level;
  const text = render(id);
  const file = pathFor(id);
  if (process.argv.includes('--print')) {
    process.stdout.write(text);
    return 0;
  }
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      // A missing file is stale.
    }
    if (current === text) {
      console.log(`music notes: ok (${file.replace(ROOT, '')})`);
      return 0;
    }
    const a = current.split('\n');
    const b = text.split('\n');
    let i = 0;
    while (i < a.length && i < b.length && a[i] === b[i]) i++;
    console.error(`${file.replace(ROOT, '')} is stale: first difference at line ${i + 1}`);
    console.error(`  committed: ${a[i] ?? '(end of file)'}`);
    console.error(`  generated: ${b[i] ?? '(end of file)'}`);
    console.error('run `bun tools/music/notes.ts` and commit the result');
    return 1;
  }
  mkdirSync(`${ROOT}assets/music/notes`, { recursive: true });
  writeFileSync(file, text);
  console.log(`wrote ${file.replace(ROOT, '')}`);
  return 0;
}

if (import.meta.main) process.exit(main());
