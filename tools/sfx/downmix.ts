//
//   bun tools/sfx/downmix.ts           regenerates the file
//   bun tools/sfx/downmix.ts --check   regenerates in memory; exits non-zero with a diff if the committed file differs
// The output depends only on the committed source and the converter: there is no clock and no unseeded randomness. The effect is
// every entry of `EFFECTS`, written in order, so effect id `n` is entry `n` of every table (the cluck is ids 0 to 3).

import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { EFFECTS, EFFECT_NAMES } from '../../assets/sfx/effects.ts';
import { convertSfx, type Conversion } from './convert.ts';

export const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const OUT = `${ROOT}crates/fizz-sfx/src/data.rs`;

const hex = (n: number): string => `0x${n.toString(16).padStart(2, '0')}`;

/** Converts every effect, in effect-id order. */
export function convertAll(): Conversion[] {
  if (EFFECTS.length === 0) throw new Error('assets/sfx/effects.ts defines no effects');
  return EFFECTS.map((v) => convertSfx(v));
}

export function emit(): string {
  const conv = convertAll();
  const oplStatics = conv.map((c, i) => {
    const rows = c.opl.records.map((r) => `    OplStep::new(${r.bank}, ${hex(r.reg)}, ${hex(r.val)}, ${r.wait}),`);
    return `/// Effect ${i} (${EFFECT_NAMES[i]}): ${c.opl.records.length} records (${c.opl.records.length * 4} bytes), ${c.opl.ticks} ticks, ${(c.opl.ticks / 560 * 1000).toFixed(0)} ms.
#[rustfmt::skip]
static OPL_${i}: [OplStep; ${c.opl.records.length}] = [
${rows.join('\n')}
];`;
  });
  const speakerStatics = conv.map((c, i) => {
    const d = c.speaker.divisors;
    const rows: string[] = [];
    for (let k = 0; k < d.length; k += 12) rows.push(`    ${d.slice(k, k + 12).join(', ')},`);
    return `/// Effect ${i} (${EFFECT_NAMES[i]}): ${d.length} frames (${d.length * 2} bytes), ${(d.length / 140 * 1000).toFixed(0)} ms.
#[rustfmt::skip]
static SPEAKER_${i}: [u16; ${d.length}] = [
${rows.join('\n')}
];`;
  });
  const n = conv.length;
  const list = (prefix: string): string => conv.map((_, i) => `&${prefix}_${i}`).join(', ');
  return `// Generated OPL2 and PC speaker data for the sound effects; do not edit.
//
// Generated by tools/sfx/downmix.ts from assets/sfx/effects.ts (the Undertone source), converted by tools/sfx/convert.ts.
// Regenerate with \`bun tools/sfx/downmix.ts\`; \`--check\` fails if this file is out of date.
//
// (c) Copyright 2026 Liminal HQ, Scott Morris
// SPDX-License-Identifier: Apache-2.0 OR MIT

use crate::OplStep;

/// The number of effects in the source (the cluck variants are the first four; \`fizz_ep2::CLUCK_VARIANTS\` of them).
pub const VARIANTS: usize = ${n};

${oplStatics.join('\n\n')}

/// The OPL2 records of each variant: writes to channel 5 timed in 560 Hz ticks.
pub(crate) static OPL: [&[OplStep]; VARIANTS] = [${list('OPL')}];

/// The length of each variant's OPL2 chunk in 560 Hz ticks.
pub(crate) static OPL_TICKS: [u32; VARIANTS] = [${conv.map((c) => c.opl.ticks).join(', ')}];

${speakerStatics.join('\n\n')}

/// The PC speaker divisors of each variant, one per 140 Hz frame; 0 is gate off.
pub(crate) static SPEAKER: [&[u16]; VARIANTS] = [${list('SPEAKER')}];
`;
}

/** The most register writes any one 560 Hz tick of a chunk makes (one channel; the OPL3 pair makes this on each of two). */
export function maxWritesPerTick(records: Conversion['opl']['records']): number {
  let best = 0;
  let run = 0;
  for (const r of records) {
    run++;
    best = Math.max(best, run);
    if (r.wait > 0) run = 0;
  }
  return best;
}

if (import.meta.main && process.argv.includes('--stats')) {
  // Per effect: records and bytes, length, the busiest tick, and the speaker list, as docs/SOUND.md tabulates them.
  let opl = 0;
  let spk = 0;
  console.log('id  name                 records  bytes  ms   max/tick  speaker frames  bytes');
  convertAll().forEach((c, i) => {
    opl += c.opl.records.length * 4;
    spk += c.speaker.divisors.length * 2;
    console.log(
      `${String(i).padStart(2)}  ${EFFECT_NAMES[i].padEnd(20)} ${String(c.opl.records.length).padStart(7)}  ${String(c.opl.records.length * 4).padStart(5)}  ${((c.opl.ticks * 1000) / 560).toFixed(0).padStart(4)}  ${String(maxWritesPerTick(c.opl.records)).padStart(8)}  ${String(c.speaker.divisors.length).padStart(14)}  ${String(c.speaker.divisors.length * 2).padStart(5)}`,
    );
  });
  console.log(`total OPL ${opl} bytes, speaker ${spk} bytes`);
} else if (import.meta.main) {
  const text = emit();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {
      // A missing file differs from any output.
    }
    if (current !== text) {
      const dir = mkdtempSync(`${tmpdir()}/sfx-check-`);
      writeFileSync(`${dir}/expected.rs`, text);
      const d = spawnSync('diff', ['-u', OUT, `${dir}/expected.rs`], { encoding: 'utf8' });
      process.stderr.write((d.stdout ?? '').split('\n').slice(0, 60).join('\n'));
      console.error('\ncrates/fizz-sfx/src/data.rs is out of date; run: bun tools/sfx/downmix.ts');
      process.exit(1);
    }
    console.log('fizz-sfx data.rs: up to date');
  } else {
    writeFileSync(OUT, text);
  }
}
