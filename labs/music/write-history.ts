import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PATHFINDER_RULES, PATTERN_BRIEF, historyOf, type Turn } from './provenance.ts';
import { TUNES } from './tunes.ts';

const TARGET = join(import.meta.dir, '..', '..', 'docs', 'MUSIC-LAB-HISTORY.md');

const KIND: Record<Turn['kind'], string> = { brief: 'asked', reply: 'answered', note: 'noted' };
const shared = new Set([...PATTERN_BRIEF, ...PATHFINDER_RULES]);

function turn(t: Turn): string {
  // The two long briefs are printed once at the top; under each tune they are pointed to rather than repeated.
  const text = t.text.filter((paragraph) => !shared.has(paragraph));
  const lines = [`**${t.speaker} ${KIND[t.kind]}:**`, '', ...text.flatMap((paragraph) => [`> ${paragraph}`, '>']).slice(0, -1)];
  if (t.text.length !== text.length) lines.push('>', `> (the ${t.text.some((p) => PATTERN_BRIEF.includes(p)) ? 'pattern brief' : 'rules of Pathfinder'}, above)`);
  if (t.block) lines.push('', '```text', t.block, '```');
  return lines.join('\n');
}

const document = [
  '# Music Lab history',
  '',
  'This is the conversation behind every tune in the [Music Lab](MUSIC-LAB.md): what the Haiku agents were asked, what they answered, and what the composer (Claude, working in this repository) made of it. It is generated by `labs/music/write-history.ts` from `labs/music/provenance.ts`, `patterns.ts` and `paths.ts`; edit those and run the script, not this file. The agents\' pictures, paths and words are as they wrote them. The briefs are as they were sent, with two things left out: the closing instructions on how to lay out the answer, and, in a relay, the first player\'s half, which the second player\'s brief quoted in full and which appears here just above it.',
  '',
  'There were two conversations. In the first, one agent drew six pictures, and tunes 1 to 8 were written from them. In the second, four agents played a game called Pathfinder, and tunes 9 to 14 were written from the paths they walked; two of those paths were begun by one agent and finished by another.',
  '',
  '## The pattern brief',
  '',
  'Sent once, to one Haiku agent. Its six answers appear under the tunes that use them.',
  '',
  ...PATTERN_BRIEF.flatMap((paragraph) => [`> ${paragraph}`, '>']).slice(0, -1),
  '',
  '## The rules of Pathfinder',
  '',
  'Sent to all four players in the same words, each followed by the place or places that player was given.',
  '',
  ...PATHFINDER_RULES.flatMap((paragraph) => [`> ${paragraph}`, '>']).slice(0, -1),
  '',
  ...TUNES.flatMap((tune, index) => [
    `## ${index + 1}. ${tune.title}`,
    '',
    `${tune.kind}, for ${tune.level.charAt(0).toLowerCase()}${tune.level.slice(1)}. ${tune.keyName}, ${tune.track.bpm} bpm.`,
    '',
    ...historyOf(tune).flatMap((t) => [turn(t), '']),
  ]),
].join('\n');

if (process.argv.includes('--check')) {
  let committed = '';
  try {
    committed = readFileSync(TARGET, 'utf8');
  } catch {
    // Reported below as stale.
  }
  if (committed !== document) {
    console.error('docs/MUSIC-LAB-HISTORY.md is stale: run `bun labs/music/write-history.ts`');
    process.exit(1);
  }
  console.log('Music Lab history: up to date');
} else {
  writeFileSync(TARGET, document);
  console.log(`wrote ${TARGET}`);
}
