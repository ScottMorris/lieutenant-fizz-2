# The plain inputs are rebuilt by `plain()` in tests/inflate.rs; keep the two recipes in step.
import zlib

TEXT = (
    "Lieutenant Fizz walks past the red door, grabs the blue key, and the chicken clucks twice. "
    "Snacks are worth ten points; the chicken is worth none. Fizz jumps, Fizz lands, Fizz waits. "
)


def plain(name):
    if name == "text":
        return (TEXT * 6).encode()
    if name == "run":
        return b"a" * 1000 + b"abc" * 100 + bytes(range(256)) * 2
    if name == "short":
        return b"hello, hello, hello"
    if name == "empty":
        return b""
    if name == "noise":
        x, out = 12345, bytearray()
        for _ in range(900):
            x = (x * 1103515245 + 12345) & 0x7FFFFFFF
            out.append(b"eeeeettttaaoonnissrh dlu"[(x >> 16) % 24])
        return bytes(out) + bytes(out[:200])
    raise KeyError(name)


def raw(data, level, strategy=zlib.Z_DEFAULT_STRATEGY):
    c = zlib.compressobj(level, zlib.DEFLATED, -15, 9, strategy)
    return c.compress(data) + c.flush()


def btype(stream):
    return (stream[0] >> 1) & 3


cases = [
    ("STORED_TEXT", "text", raw(plain("text"), 0), 0),
    ("STORED_EMPTY", "empty", raw(plain("empty"), 0), 0),
    ("FIXED_SHORT", "short", raw(plain("short"), 9, zlib.Z_FIXED), 1),
    ("FIXED_RUN", "run", raw(plain("run"), 9, zlib.Z_FIXED), 1),
    ("DYNAMIC_TEXT", "text", raw(plain("text"), 9), 2),
    ("DYNAMIC_NOISE", "noise", raw(plain("noise"), 9), 2),
]
print("// Generated by tests/gen_vectors.py from Python's zlib (raw deflate, wbits -15). Do not edit.")
print("//")
print("// (c) Copyright 2026 Liminal HQ, Scott Morris")
print("// SPDX-License-Identifier: Apache-2.0 OR MIT")
print()
print("#![allow(dead_code)]")
print()
print("/// (name, plain-input recipe, deflate stream, first block type: 0 stored, 1 fixed, 2 dynamic)")
print("pub const VECTORS: &[(&str, &str, &[u8], u8)] = &[")
for name, recipe, s, want in cases:
    assert btype(s) == want, (name, btype(s))
    assert zlib.decompress(s, -15) == plain(recipe)
    body = ", ".join(str(b) for b in s)
    print(f'    ("{name}", "{recipe}", &[{body}], {want}),')
print("];")
